"""JSON parsing and schema validation for structured LLM outputs."""

import json
from typing import Any

from jsonschema import (
    Draft202012Validator,
    SchemaError,
)
from jsonschema import (
    ValidationError as JsonSchemaValidationError,
)
from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
)
from pydantic import (
    ValidationError as PydanticValidationError,
)


class AssistantStructuredResponse(BaseModel):
    """Validated response contract for structured assistant output."""

    model_config = ConfigDict(
        extra="forbid",
        strict=True,
        allow_inf_nan=False,
    )

    answer: str = Field(min_length=1)
    confidence: float = Field(ge=0.0, le=1.0)


class StructuredOutputError(Exception):
    """Base exception for structured output processing errors."""


class StructuredOutputSchemaError(StructuredOutputError):
    """Raised when a JSON Schema is invalid."""


class StructuredOutputValidationError(StructuredOutputError):
    """Raised when parsed JSON does not match the expected schema."""


class StructuredOutputParsingError(StructuredOutputError):
    """Raised when generated text is not valid JSON."""


def parse_json(text: str) -> Any:
    """Parse a JSON string into a Python object.

    Args:
        text: The raw JSON text generated by the language model.

    Returns:
        The Python object represented by the JSON document.

    Raises:
        StructuredOutputParsingError: If the text is not valid JSON.
        TypeError: If the input is not a string.
    """
    if not isinstance(text, str):
        raise TypeError("JSON input must be a string.")

    try:
        return json.loads(text)
    except json.JSONDecodeError as exc:
        raise StructuredOutputParsingError(
            f"Generated text is not valid JSON: {exc.msg}."
        ) from exc


def validate_json_schema(
    data: Any,
    schema: dict[str, Any],
) -> None:
    """Validate parsed JSON data against a JSON Schema.

    Args:
        data: The parsed Python object to validate.
        schema: The JSON Schema describing the expected structure.

    Raises:
        StructuredOutputSchemaError: If the schema itself is invalid.
        StructuredOutputValidationError: If the data violates the schema.
    """
    try:
        Draft202012Validator.check_schema(schema)
    except SchemaError as exc:
        raise StructuredOutputSchemaError(
            f"Invalid JSON Schema: {exc.message}"
        ) from exc

    validator = Draft202012Validator(schema)
    errors = sorted(
        validator.iter_errors(data),
        key=lambda error: list(map(str, error.absolute_path)),
    )

    if errors:
        error = errors[0]
        location = ".".join(map(str, error.absolute_path)) or "<root>"

        raise StructuredOutputValidationError(
            f"JSON Schema validation failed at '{location}': {error.message}"
        )


def parse_and_validate_json(
    text: str,
    schema: dict[str, Any],
) -> Any:
    """Parse JSON text and validate it against a JSON Schema."""
    data = parse_json(text)
    validate_json_schema(data, schema)
    return data


def parse_and_validate_model(
    text: str,
    model_type: type[BaseModel],
) -> BaseModel:
    """Parse generated JSON and validate it against a Pydantic model."""
    data = parse_json(text)

    try:
        return model_type.model_validate(data)
    except PydanticValidationError as exc:
        raise StructuredOutputValidationError(
            f"Pydantic validation failed: {exc}"
        ) from exc
